const n = (x, y) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
function oval(cx, cy, rx, ry, steps = 16) {
	const points = [];
	for (let i = 0; i <= steps; i++) {
		const a = i / steps * Math.PI * 2;
		points.push(n(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry));
	}
	return points;
}
function circ(cx, cy, r, steps = 12) { return oval(cx, cy, r, r, steps); }
function poly(pairs) {
	const points = pairs.map(([x, y]) => n(x, y));
	const first = points[0], last = points[points.length - 1];
	if (first[0] !== last[0] || first[1] !== last[1]) points.push([first[0], first[1]]);
	return points;
}
function line(pairs) { return pairs.map(([x, y]) => n(x, y)); }
function curve(start, bends) {
	let [x, y] = start;
	const points = [n(x, y)];
	for (const [cx, cy, x1, y1] of bends) {
		for (let i = 1; i <= 7; i++) {
			const t = i / 7, u = 1 - t;
			points.push(n(u * u * x + 2 * u * t * cx + t * t * x1, u * u * y + 2 * u * t * cy + t * t * y1));
		}
		x = x1; y = y1;
	}
	return points;
}
function bloom(x, y, r, petals = 6) {
	const parts = [];
	for (let i = 0; i < petals; i++) {
		const a = -Math.PI / 2 + i / petals * Math.PI * 2;
		parts.push(circ(x + Math.cos(a) * r * 0.78, y + Math.sin(a) * r * 0.78, r * 0.36, 8));
	}
	parts.push(circ(x, y, r * 0.22, 8));
	return parts;
}
function stem(x, y, h) {
	return [
		line([[x, y], [x, y - h]]),
		poly([[x, y - h * 0.42], [x - 16, y - h * 0.62], [x, y - h * 0.58]]),
		poly([[x, y - h * 0.68], [x + 16, y - h * 0.86], [x, y - h * 0.82]]),
	];
}
const W = 120, H = 160;
function page(name, parts) { return {name, w: W, h: H, parts}; }

