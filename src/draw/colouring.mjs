export function colouringGlyph(page) {
	let d = '';
	for (const part of page.parts) {
		d += 'M' + part[0][0] + ' ' + part[0][1];
		for (let i = 1; i < part.length; i++) d += 'L' + part[i][0] + ' ' + part[i][1];
		const first = part[0], last = part[part.length - 1];
		if (first[0] === last[0] && first[1] === last[1]) d += 'Z';
	}
	return {d, w: page.w, h: page.h, width: (Math.max(page.w, page.h) / 14).toFixed(2)};
}
