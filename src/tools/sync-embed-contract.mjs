import {readFile, writeFile} from 'node:fs/promises';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {PICTURE_BYTES} from '../images/limits.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BEGIN = '// ---- BEGIN contract.mjs (generated by tools/sync-embed-contract.mjs; edit contract.mjs) ----';
export const END = '// ---- END contract.mjs ----';
export const PICTURE_BYTES_LINE = 'const PICTURE_BYTES = ' + PICTURE_BYTES + ';';

export function syncedContract(contract) {
	const pattern = /^const PICTURE_BYTES = [^\n]*\n/m;
	if (!pattern.test(contract)) throw new Error('contract.mjs has no generated PICTURE_BYTES line');
	return contract.replace(pattern, PICTURE_BYTES_LINE + '\n');
}

export async function embedWithContract({root: base = root} = {}) {
	const rawContract = await readFile(resolve(base, 'packages/rapier-embed/contract.mjs'), 'utf8');
	const contract = syncedContract(rawContract);
	const names = [...contract.matchAll(/^export (?:async )?(?:const|let|function\*?|class) ([A-Za-z_$][\w$]*)/gm)].map(match => match[1]);
	const inner = contract.replace(/^\/\/ SPDX-License-Identifier:[^\n]*\n/, '').replace(/^export /gm, '').trimEnd();
	const body = 'const {' + names.join(', ') + '} = (() => {\n' + inner + '\nreturn {' + names.join(', ') + '};\n})();';
	const embed = await readFile(resolve(base, 'packages/rapier-embed/embed.mjs'), 'utf8');
	const block = BEGIN + '\n' + body + '\n' + END;
	const start = embed.indexOf(BEGIN), end = embed.indexOf(END);
	if (start >= 0 && end > start) return {contract: rawContract, nextContract: contract, embed, next: embed.slice(0, start) + block + embed.slice(end + END.length)};
	const importLine = /^import \{[^}]*\} from '\.\/contract\.mjs';\n/m;
	if (!importLine.test(embed)) throw new Error('embed.mjs has neither the contract markers nor the contract import');
	return {contract: rawContract, nextContract: contract, embed, next: embed.replace(importLine, block + '\n')};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const {contract, nextContract, embed, next} = await embedWithContract();
	if (process.argv.includes('--check')) {
		if (contract !== nextContract || embed !== next) { console.error('embed.mjs or contract.mjs differs from images/limits.mjs'); process.exit(1); }
	} else {
		if (contract !== nextContract) await writeFile(resolve(root, 'packages/rapier-embed/contract.mjs'), nextContract);
		await writeFile(resolve(root, 'packages/rapier-embed/embed.mjs'), next);
	}
	console.log('embed.mjs carries contract.mjs');
}
