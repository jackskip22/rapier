function verifyOwnerExports() {
  const failures = [];
  for (const [name, value] of [
    ['PICTURE_BYTES', PICTURE_BYTES],
    ['PICTURE_EDGE', PICTURE_EDGE],
    ['ASSET_PIXELS', ASSET_PIXELS],
    ['PLAYBACK_PIXELS', PLAYBACK_PIXELS],
    ['JPEG_XL_ENCODE_PIXELS', JPEG_XL_ENCODE_PIXELS],
    ['KEPT_JPEG_PIXELS', KEPT_JPEG_PIXELS],
    ['PICTURE_BASE64_URL_CHARS', PICTURE_BASE64_URL_CHARS],
    ['PICTURE_PERCENT_URL_CHARS', PICTURE_PERCENT_URL_CHARS],
  ]) {
    if (!Number.isSafeInteger(value) || value < 1) failures.push(`${OWNER_PATH}: ${name} must be a positive safe integer`);
  }
  if (!Object.isFrozen(PICTURE_LIMITS) || !Object.isFrozen(JPEG_XL_LIMITS) || !Object.isFrozen(JPEG_XL_PICTURE_LIMITS))
    failures.push(`${OWNER_PATH}: PICTURE_LIMITS, JPEG_XL_LIMITS, and JPEG_XL_PICTURE_LIMITS must be frozen`);
  if (JPEG_XL_LIMITS.bytes !== PICTURE_BYTES || JPEG_XL_LIMITS.edge !== PICTURE_EDGE || JPEG_XL_LIMITS.pixels !== JPEG_XL_ENCODE_PIXELS)
    failures.push(`${OWNER_PATH}: JPEG_XL_LIMITS must project PICTURE_BYTES, PICTURE_EDGE, and JPEG_XL_ENCODE_PIXELS`);
  if (JPEG_XL_PICTURE_LIMITS.bytes !== PICTURE_BYTES || JPEG_XL_PICTURE_LIMITS.edge !== PICTURE_EDGE || JPEG_XL_PICTURE_LIMITS.pixels !== KEPT_JPEG_PIXELS)
    failures.push(`${OWNER_PATH}: JPEG_XL_PICTURE_LIMITS must project PICTURE_BYTES, PICTURE_EDGE, and KEPT_JPEG_PIXELS`);
  return failures;
}

