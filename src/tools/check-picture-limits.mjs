const CODE_EXTENSIONS = new Set(['.js', '.mjs', '.mts', '.ts']);

function collectFilesSync(targetPath, root, skipped, out) {
  const rel = relative(root, targetPath).replaceAll('\\', '/');
  if (rel && !rel.startsWith('..')) {
    const reason = skipReason(rel) || skipReason(rel + '/');
    if (reason) {
      skipped.push({path: rel, why: reason});
      return;
    }
  }
  let info;
  try { info = statSync(targetPath); }
  catch (error) {
    if (error?.code === 'ENOENT') return;
    throw error;
  }
  if (info.isFile()) {
    if (CODE_EXTENSIONS.has(extname(targetPath))) out.push([targetPath, rel]);
    return;
  }
  if (!info.isDirectory()) return;
  const entries = readdirSync(targetPath, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const child = join(targetPath, entry.name);
    const childRel = (rel ? rel + '/' + entry.name : entry.name) + (entry.isDirectory() ? '/' : '');
    const reason = !childRel.startsWith('..') ? skipReason(childRel) : null;
    if (reason) {
      skipped.push({path: childRel, why: reason});
      continue;
    }
    if (entry.isDirectory()) collectFilesSync(child, root, skipped, out);
    else if (entry.isFile() && CODE_EXTENSIONS.has(extname(entry.name))) out.push([child, rel ? rel + '/' + entry.name : entry.name]);
  }
}

export async function checkPictureLimits({root = REPO_ROOT, paths = null} = {}) {
  const started = performance.now();
  const failures = verifyOwnerExports();
  const skipped = [];
  const roots = paths && paths.length ? paths.map(p => resolve(p)) : SCANNED_TREES.map(tree => join(root, tree));
  const files = [];
  for (const target of roots) collectFilesSync(target, root, skipped, files);

  const scannedRels = new Set(files.map(([, rel]) => rel));
  if (scannedRels.has('packages/rapier-embed/contract.mjs') || scannedRels.has('packages/rapier-embed/embed.mjs')) {
    try {
      const {contract, nextContract, embed, next} = await embedWithContract({root});
      if (/(?:^|\n)\s*(?:import|export)\s+[^'"]*?from\s+['"]\.\.\//.test(contract)) {
        failures.push('packages/rapier-embed/contract.mjs: must not import from outside packages/rapier-embed/ (run node tools/sync-embed-contract.mjs)');
      }
      if (contract !== nextContract) {
        failures.push('packages/rapier-embed/contract.mjs: generated PICTURE_BYTES line differs from images/limits.mjs; run node tools/sync-embed-contract.mjs');
      }
      const beginAt = embed.indexOf(EMBED_BEGIN), endAt = embed.indexOf(EMBED_END);
      const block = beginAt >= 0 && endAt > beginAt ? embed.slice(beginAt, endAt + EMBED_END.length) : '';
      if (embed !== next || !block.includes('\n' + PICTURE_BYTES_LINE + '\n')) {
        failures.push('packages/rapier-embed/embed.mjs: generated contract.mjs block differs from images/limits.mjs; run node tools/sync-embed-contract.mjs');
      }
    } catch (error) {
      if (error?.code !== 'ENOENT') {
        failures.push('packages/rapier-embed/embed.mjs: ' + String(error?.message || error) + '; run node tools/sync-embed-contract.mjs');
      }
    }
  }

  const violations = [];
  for (const [filePath, rel] of files) {
    const bytes = readFileSync(filePath);
    for (const hit of findPictureLimitCopiesInBytes(bytes, rel)) violations.push(hit);
  }
  violations.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);

  for (const v of violations) {
    const constantName = TARGET_NAMES.get(v.value);
    failures.push(
      `${v.file}:${v.line}: written-out picture limit ${v.spelling} (${v.value}); read ${constantName} from ${OWNER_PATH} instead`
    );
  }
  return {
    ok: failures.length === 0,
    filesScanned: files.length,
    skipped,
    failures,
    elapsedMs: Math.round((performance.now() - started) * 10) / 10,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const showSkipped = args.includes('--show-skips');
  const targetArgs = args.filter(arg => !arg.startsWith('--'));
  const result = await checkPictureLimits({paths: targetArgs.length ? targetArgs : null});
  if (showSkipped) {
    for (const row of result.skipped) console.log(`skip ${row.path}: ${row.why}`);
  }
  if (!result.ok) {
    for (const message of result.failures) console.error(message);
    process.exitCode = 1;
  } else {
    console.log(`check-picture-limits: ${result.filesScanned} files checked in ${result.elapsedMs} ms (${result.skipped.length} paths skipped); all shared picture limits read from ${OWNER_PATH}`);
  }
}
