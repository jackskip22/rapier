const MAX_RUN = 512;
const RUN_OP = new Uint8Array(MAX_RUN);
const RUN_VAL = new Float64Array(MAX_RUN);
const RUN_START = new Int32Array(MAX_RUN);
const RUN_END = new Int32Array(MAX_RUN);
const RUN_COVERED = new Uint8Array(MAX_RUN);
const PREFIX_BUF = new Uint8Array(64);
const TMPL_STACK = new Int32Array(64);
let scratchBuf = new Uint8Array(4 * 1024 * 1024);

let evalPos = 0;
let evalTo = 0;

function parsePrimary() {
  if (evalPos >= evalTo) return NaN;
  const op = RUN_OP[evalPos];
  if (op === 0) return RUN_VAL[evalPos++];
  if (op === 1) {
    evalPos++;
    const v = parseBitOr();
    if (evalPos >= evalTo || RUN_OP[evalPos] !== 2) return NaN;
    evalPos++;
    return v;
  }
  return NaN;
}

function parseUnary() {
  if (evalPos < evalTo) {
    const op = RUN_OP[evalPos];
    if (op === 3 || op === 4 || op === 5) {
      evalPos++;
      const v = parseUnary();
      return op === 3 ? +v : op === 4 ? -v : ~v;
    }
  }
  return parsePrimary();
}

function parseExp() {
  const base = parseUnary();
  if (evalPos < evalTo && RUN_OP[evalPos] === 7) {
    evalPos++;
    const exp = parseExp();
    return Math.abs(exp) > 1024 ? NaN : base ** exp;
  }
  return base;
}

function parseMul() {
  let v = parseExp();
  while (evalPos < evalTo) {
    const op = RUN_OP[evalPos];
    if (op !== 6 && op !== 8 && op !== 9) break;
    evalPos++;
    const r = parseExp();
    v = op === 6 ? v * r : op === 8 ? v / r : v % r;
  }
  return v;
}

function parseAdd() {
  let v = parseMul();
  while (evalPos < evalTo) {
    const op = RUN_OP[evalPos];
    if (op !== 3 && op !== 4) break;
    evalPos++;
    const r = parseMul();
    v = op === 3 ? v + r : v - r;
  }
  return v;
}

function parseShift() {
  let v = parseAdd();
  while (evalPos < evalTo) {
    const op = RUN_OP[evalPos];
    if (op !== 10 && op !== 11 && op !== 12) break;
    evalPos++;
    const r = parseAdd();
    if (r < 0 || r > 31) return NaN;
    v = op === 10 ? (v << r) : op === 11 ? (v >> r) : (v >>> r);
  }
  return v;
}

function parseBitAnd() {
  let v = parseShift();
  while (evalPos < evalTo && RUN_OP[evalPos] === 14) { evalPos++; v = (v & parseShift()); }
  return v;
}

function parseBitXor() {
  let v = parseBitAnd();
  while (evalPos < evalTo && RUN_OP[evalPos] === 15) { evalPos++; v = (v ^ parseBitAnd()); }
  return v;
}

function parseBitOr() {
  let v = parseBitXor();
  while (evalPos < evalTo && RUN_OP[evalPos] === 13) { evalPos++; v = (v | parseBitXor()); }
  return v;
}

function evalConstantSlice(from, to) {
  evalPos = from;
  evalTo = to;
  const result = parseBitOr();
  return evalPos === to && Number.isFinite(result) ? result : NaN;
}

function lineNumberAt(bytes, offset) {
  let line = 1;
  for (let i = 0; i < offset; i++) {
    const c = bytes[i];
    if (c === 10) line++;
    else if (c === 13) {
      line++;
      if (bytes[i + 1] === 10) i++;
    }
  }
  return line;
}

function lineTextAt(bytes, len, offset) {
  let start = offset;
  while (start > 0 && bytes[start - 1] !== 10 && bytes[start - 1] !== 13) start--;
  let end = offset;
  while (end < len && bytes[end] !== 10 && bytes[end] !== 13) end++;
  return Buffer.from(bytes.buffer, bytes.byteOffset + start, end - start).toString('utf8').trim();
}

function sliceAscii(bytes, start, end) {
  return Buffer.from(bytes.buffer, bytes.byteOffset + start, end - start).toString('utf8');
}

function flushRunBuffer(runLen, bytes, relPath, rawHits) {
  let startIdx = 0, endIdx = runLen;
  while (startIdx < endIdx) {
    const op = RUN_OP[startIdx];
    if (op === 0 || op === 1 || op === 3 || op === 4 || op === 5) break;
    startIdx++;
  }
  while (endIdx > startIdx) {
    const op = RUN_OP[endIdx - 1];
    if (op === 0 || op === 2) break;
    endIdx--;
  }
  if (endIdx <= startIdx) return;

  if (endIdx - startIdx === 1 && RUN_OP[startIdx] === 0) {
    const v = RUN_VAL[startIdx];
    if (isTargetValue(v)) {
      rawHits.push({
        file: relPath,
        offset: RUN_START[startIdx],
        value: v,
        spelling: sliceAscii(bytes, RUN_START[startIdx], RUN_END[startIdx]),
      });
    }
    return;
  }

  let cursor = startIdx;
  while (cursor < endIdx) {
    let matchedEnd = -1, matchedVal = NaN;
    evalPos = cursor;
    evalTo = endIdx;
    const directVal = parseBitOr();
    if (evalPos > cursor && Number.isFinite(directVal)) {
      matchedEnd = evalPos;
      matchedVal = directVal;
    } else {
      let depth = 0;
      for (let k = cursor; k < endIdx; k++) {
        const op = RUN_OP[k];
        if (op === 1) depth++;
        else if (op === 2) {
          depth--;
          if (depth < 0) break;
        }
        if (depth === 0 && (op === 0 || op === 2)) {
          const val = evalConstantSlice(cursor, k + 1);
          if (Number.isFinite(val)) { matchedEnd = k + 1; matchedVal = val; }
        }
      }
    }
    if (matchedEnd > cursor) {
      if (isTargetValue(matchedVal)) {
        let firstNumIdx = -1;
        const parts = [];
        for (let k = cursor; k < matchedEnd; k++) {
          if (RUN_OP[k] === 0) {
            if (firstNumIdx < 0) firstNumIdx = k;
            RUN_COVERED[k] = 1;
            parts.push(sliceAscii(bytes, RUN_START[k], RUN_END[k]));
          } else {
            parts.push(OP_STRINGS[RUN_OP[k]]);
          }
        }
        if (firstNumIdx >= 0) {
          rawHits.push({
            file: relPath,
            offset: RUN_START[firstNumIdx],
            value: matchedVal,
            spelling: parts.join(' '),
          });
        }
      }
      cursor = matchedEnd;
    } else {
      cursor++;
    }
  }
  for (let k = startIdx; k < endIdx; k++) {
    if (RUN_OP[k] === 0 && !RUN_COVERED[k] && isTargetValue(RUN_VAL[k])) {
      rawHits.push({
        file: relPath,
        offset: RUN_START[k],
        value: RUN_VAL[k],
        spelling: sliceAscii(bytes, RUN_START[k], RUN_END[k]),
      });
    }
  }
}

