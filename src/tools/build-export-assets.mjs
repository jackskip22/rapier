// The worker carries the same house styles as the editor: each sheet as the build writes it into the editor's page (tools/style-text.mjs),
// so a standalone page is the same bytes from the worker and from the editor.
import {existsSync} from 'node:fs';
import {writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {styleText} from './style-text.mjs';

export async function buildExportAssets() {
  const root = new URL('../', import.meta.url);
  // The door's tree carries the worker; a tree without it (the public source) has nothing to write the assets for.
  if (!existsSync(fileURLToPath(new URL('mcp/', root)))) return;
  const paths = {'rapier-content-style': 'spec/markdown-style.css', 'rapier-highlight-style': 'editor/styles/rapier-highlight.css'};
  const styles = {};
  for (const [name, path] of Object.entries(paths)) styles[name] = styleText(path);
  await writeFile(new URL('mcp/render-assets.mjs', root), '// Generated by tools/build-export-assets.mjs from the document styles.\nexport const styles = Object.freeze(' + JSON.stringify(styles) + ');\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildExportAssets();
