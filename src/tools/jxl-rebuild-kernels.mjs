import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

let optimizer;
async function binaryen() {
  if (!optimizer) optimizer = import(process.env.BINARYEN_MODULE
    ? pathToFileURL(resolve(process.env.BINARYEN_MODULE)).href : 'binaryen')
    .then(module => module.default).catch(cause => {
      optimizer = undefined;
      throw new Error('Kernel stripping needs build-time binaryen@123.0.0; set BINARYEN_MODULE to its index.js.', {cause});
    });
  return optimizer;
}

export async function stripKernelExports(bytes, keep, implementation) {
  const original = new WebAssembly.Module(bytes), exports = WebAssembly.Module.exports(original);
  const names = new Set(keep);
  if (names.size !== keep.length) throw new Error('Duplicate kernel export in the entry profile.');
  for (const name of names) if (!exports.some(item => item.name === name)) throw new Error('Missing canonical kernel export: ' + name);
  const api = implementation || await binaryen(), module = api.readBinary(bytes);
  try {
    module.setFeatures(api.Features.SIMD128 | api.Features.BulkMemory | api.Features.BulkMemoryOpt | api.Features.NontrappingFPToInt);
    for (const item of exports) if (!names.has(item.name)) module.removeExport(item.name);
    module.runPasses(['remove-unused-module-elements']);
    if (!module.validate()) throw new Error('The stripped kernel module is invalid.');
    const result = module.emitBinary();
    const emitted = WebAssembly.Module.exports(new WebAssembly.Module(result)).map(item => item.name).sort();
    if (JSON.stringify(emitted) !== JSON.stringify([...names].sort())) throw new Error('The stripped kernel interface differs from its entry profile.');
    return result;
  } finally { module.dispose(); }
}

const sha = bytes => createHash('sha256').update(bytes).digest('hex');

export function rebuildKernelSources(full, cut, storedWasmText) {
  const text = storedWasmText(cut);
  const rebuild = `// Generated by tools/jxl-rebuild-kernels.mjs from decode-kernels-bytes.mjs. MIT. Do not edit.
// REBUILD_KERNELS from decode sha256 ${sha(full)}, cut sha256 ${sha(cut)}
export const REBUILD_KERNELS = ${JSON.stringify(text)};
`;
  const thresholds = `// Generated by tools/jxl-rebuild-kernels.mjs from decode-kernels-bytes.mjs. MIT. Do not edit.
// The decoder's RGB8 thresholds (decode-kernels.wat srgb8Build) from decode sha256 ${sha(full)}: T[k], the smallest
// binary32 linear sample it writes as at least level k, as binary32 words. Roots by Newton steps: + - * / and sqrt only.
export const RGB8_THRESHOLDS = /* @__PURE__ */ (() => {
  const u = new Uint32Array(256), f = new Float32Array(u.buffer), w = new Uint32Array(1), v = new Float32Array(w.buffer);
  const root = (A, n) => { let r = 1; for (let i = 0; i < 99; i++) { const q = r * r; r = ((n - 1) * r + A / (n == 3 ? q : q * q)) / n; } return r; };
  const level = bits => {
    w[0] = bits;
    const x = v[0], y = x * x, t = Math.fround(x <= 0.0031308 ? 12.92 * x : 1.055 * Math.sqrt(Math.sqrt(root(y * y * x, 3))) - 0.055) * 255 + 0.5;
    return t >= 255.5 ? 255 : t >= 1 ? t | 0 : 0;
  };
  for (let k = 1, prev = 0; k < 256; k++) {
    const a = (k - 0.5) / 255, c = (a + 0.055) / 1.055, d = c * c * c * c;
    v[0] = a <= 0.04045 ? a / 12.92 : root(d * d * d, 5);
    let low = Math.max(prev, w[0] - 4);
    while (low > prev && level(low - 1) >= k) low--;
    while (level(low) < k) low++;
    u[k] = prev = low;
  }
  return f;
})();
`;
  return {rebuild, thresholds};
}

export async function checkRGB8Thresholds(decode, source) {
  const {RGB8_THRESHOLDS} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  if (!(RGB8_THRESHOLDS instanceof Float32Array) || RGB8_THRESHOLDS.length !== 256)
    throw new Error('rgb8-thresholds.mjs must produce 256 binary32 values');
  const {exports} = new WebAssembly.Instance(new WebAssembly.Module(decode));
  if (exports.srgb8Build(0)) throw new Error('The decoder refused to build its RGB8 thresholds');
  const expected = new Uint32Array(exports.memory.buffer, 32768, 256);
  const actual = new Uint32Array(RGB8_THRESHOLDS.buffer, RGB8_THRESHOLDS.byteOffset, 256);
  for (let i = 0; i < expected.length; i++) if (actual[i] !== expected[i])
    throw new Error('rgb8-thresholds.mjs differs from decode-kernels.wat at level ' + i);
}

