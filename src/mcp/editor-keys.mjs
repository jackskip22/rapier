import { base64url, fromBase64url } from '../agent/door-identity.mjs';

export const EDITOR_KEY_LIFETIME_MS = 24 * 60 * 60 * 1000;
const EDITOR_KEY_PREFIX = 'ek1';

export const EDITOR_SECRET_CANONICAL_BYTES = 32;
export function classifyEditorSecret(secret) {
  if (typeof secret !== 'string' || !secret.length) return { usable: false, reason: 'missing' };
  let bytes;
  if (/^[A-Za-z0-9_-]{43}$/.test(secret)) bytes = fromBase64url(secret);
  else if (/^[A-Za-z0-9+/]{43}=$/.test(secret)) bytes = Uint8Array.from(atob(secret), char => char.charCodeAt(0));
  if (!bytes || bytes.length !== EDITOR_SECRET_CANONICAL_BYTES) return { usable: false, reason: 'malformed' };
  return { usable: true, form: 'canonical', keyBytes: bytes };
}
export const editorSecretUsable = secret => classifyEditorSecret(secret).usable;
export function editorSecretKeyMaterial(secret, domain = '') {
  const classified = classifyEditorSecret(secret);
  if (!classified.usable) throw new Error('EDITOR_KEY_SECRET must encode 32 generated bytes as base64 or base64url');
  if (!domain) return classified.keyBytes;
  const prefix = new TextEncoder().encode(domain);
  const out = new Uint8Array(prefix.length + classified.keyBytes.length);
  out.set(prefix, 0); out.set(classified.keyBytes, prefix.length);
  return out;
}
async function editorKeyMac(secret, body) {
  const key = await crypto.subtle.importKey('raw', editorSecretKeyMaterial(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return base64url(new Uint8Array(await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(body))));
}
const editorKeyBody = (nonce, issued, binding) => JSON.stringify(['rapier-editor-v2', binding.workspace || '', binding.connection || '', nonce, issued]);
export async function mintEditorKey(secret, now = Date.now(), binding = {}) {
  const classified = classifyEditorSecret(secret);
  if (!classified.usable) throw new Error('EDITOR_KEY_SECRET must encode 32 generated bytes as base64 or base64url');
  const nonce = base64url(crypto.getRandomValues(new Uint8Array(16)));
  const issued = String(Math.floor(now));
  return `${EDITOR_KEY_PREFIX}.${nonce}.${issued}.${await editorKeyMac(secret, editorKeyBody(nonce, issued, binding))}`;
}
export async function verifyEditorKey(secret, key, now = Date.now(), binding = {}) {
  if (!editorSecretUsable(secret)) return { ok: false, reason: 'unconfigured' };
  const parts = typeof key === 'string' ? key.split('.') : [];
  if (parts.length !== 4 || parts[0] !== EDITOR_KEY_PREFIX || !/^[A-Za-z0-9_-]{22}$/.test(parts[1]) || !/^\d{1,16}$/.test(parts[2])) return { ok: false, reason: 'malformed' };
  const issued = Number(parts[2]);
  if (!(issued <= now + 60_000)) return { ok: false, reason: 'future' };
  if (now - issued > EDITOR_KEY_LIFETIME_MS) return { ok: false, reason: 'expired' };
  if (!/^[A-Za-z0-9_-]{43}$/.test(parts[3])) return { ok: false, reason: 'forged' };
  const signature = fromBase64url(parts[3]);
  if (base64url(signature) !== parts[3]) return { ok: false, reason: 'forged' };
  const verifier = await crypto.subtle.importKey('raw', editorSecretKeyMaterial(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['verify']);
  const valid = await crypto.subtle.verify('HMAC', verifier, signature, new TextEncoder().encode(editorKeyBody(parts[1], parts[2], binding)));
  return valid ? { ok: true, issuedAt: issued } : { ok: false, reason: 'forged' };
}

export async function mintEditorTicket(secret, document, authority, now = Date.now()) {
  const {source, ownerId, connectionId, scopes, grant} = authority;
  const payload = base64url(new TextEncoder().encode(JSON.stringify({document, authority: {source, ownerId, connectionId, scopes, grant}, issued: now})));
  return 'et1.' + payload + '.' + await editorKeyMac(secret, 'rapier-editor-transport:' + payload);
}
export async function verifyEditorTicket(secret, ticket, now = Date.now()) {
  if (!editorSecretUsable(secret) || typeof ticket !== 'string' || ticket.length > 8192) return null;
  const parts = ticket.split('.');
  if (parts.length !== 3 || parts[0] !== 'et1' || !/^[A-Za-z0-9_-]+$/.test(parts[1]) || !/^[A-Za-z0-9_-]{43}$/.test(parts[2])) return null;
  try {
    const key = await crypto.subtle.importKey('raw', editorSecretKeyMaterial(secret), {name: 'HMAC', hash: 'SHA-256'}, false, ['verify']);
    if (!await crypto.subtle.verify('HMAC', key, fromBase64url(parts[2]), new TextEncoder().encode('rapier-editor-transport:' + parts[1]))) return null;
    const value = JSON.parse(new TextDecoder().decode(fromBase64url(parts[1])));
    if (!Number.isSafeInteger(value.issued) || value.issued > now + 60000 || now - value.issued > EDITOR_KEY_LIFETIME_MS ||
        !/^rpr_[A-Za-z0-9_-]{43}$/.test(value.document) || !['anonymous', 'oauth', 'server'].includes(value.authority?.source)) return null;
    return value;
  } catch { return null; }
}
